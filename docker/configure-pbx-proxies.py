#!/usr/bin/env python3
"""Generate TLS reverse-proxy listeners for each enrolled PBX dashboard.

The gateway already has a loopback FRP endpoint per PBX (for example
127.0.0.1:23009).  Each PBX gets a stable public port derived from that API
port (39000 + port % 100), so the PBX dashboard's root-relative assets and API
calls keep working unchanged.

Access is gated by the existing control-dashboard session cookie through
nginx auth_request.  The PBX's own login remains the second factor.
"""
import json
import os
from pathlib import Path
from urllib.parse import urlsplit

CONTROL_DATA_FILE = Path(os.environ.get('CONTROL_DATA_FILE', '/var/lib/sokrat-gateway/control.json'))
OUTPUT = Path(os.environ.get('PBX_PROXY_CONFIG', '/etc/nginx/conf.d/sokrat-pbx-proxies.conf'))
CONTROL_PORT = int(os.environ.get('CONTROL_PORT', '8002'))
TLS_DIR = os.environ.get('GATEWAY_TLS_DIR', '/etc/sokrat/tls')
PORT_BASE = 39000
API_BASE = 23000
API_MAX = 23099


def proxy_port(api_port):
    if not isinstance(api_port, int) or not (API_BASE <= api_port <= API_MAX):
        return None
    port = PORT_BASE + (api_port % 100)
    return port if PORT_BASE <= port <= PORT_BASE + 99 else None


def main():
    try:
        data = json.loads(CONTROL_DATA_FILE.read_text())
    except FileNotFoundError:
        data = {'pbx': []}
    except Exception as error:
        raise SystemExit('cannot read control store: ' + str(error))
    entries = []
    seen = set()
    for record in data.get('pbx', []):
        if not record.get('enabled'):
            continue
        try:
            parsed = urlsplit(record.get('apiURL', ''))
            api_port = parsed.port
        except ValueError:
            continue
        if parsed.hostname not in ('127.0.0.1', 'localhost'):
            continue
        public = proxy_port(api_port)
        if public is None or public in seen:
            continue
        seen.add(public)
        entries.append((public, api_port, str(record.get('name') or record.get('id') or 'PBX')))
    entries.sort()
    lines = [
        '# Generated by configure-pbx-proxies.py. Do not edit by hand.',
        'map $http_upgrade $sokrat_pbx_connection {',
        '    default upgrade;',
        "    '' close;",
        '}',
        'map $server_port $sokrat_pbx_api {',
    ]
    for public, api_port, _name in entries:
        lines.append(f'    {public} {api_port};')
    lines += ['}', '']
    if entries:
        listens = ' '.join(f'listen {public} ssl;' for public, _api, _name in entries)
        lines += [
            'server {',
            '    ' + listens,
            '    server_name _;',
            f'    ssl_certificate {TLS_DIR}/fullchain.pem;',
            f'    ssl_certificate_key {TLS_DIR}/privkey.pem;',
            '    ssl_protocols TLSv1.2 TLSv1.3;',
            '    ssl_session_cache shared:sokrat_pbx_cache:10m;',
            '    ssl_session_timeout 1h;',
            '',
            '    location = /_sokrat_control_auth {',
            '        internal;',
            f'        proxy_pass http://127.0.0.1:{CONTROL_PORT}/control/api/state;',
            '        proxy_pass_request_body off;',
            '        proxy_set_header Content-Length "";',
            '        proxy_set_header Cookie $http_cookie;',
            '        proxy_set_header Host $host;',
            '    }',
            '',
            '    location / {',
            '        auth_request /_sokrat_control_auth;',
            '        error_page 401 = @sokrat_login;',
            '        proxy_pass http://127.0.0.1:$sokrat_pbx_api;',
            '        proxy_http_version 1.1;',
            '        proxy_set_header Host $http_host;',
            '        proxy_set_header X-Real-IP $remote_addr;',
            '        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;',
            '        proxy_set_header X-Forwarded-Proto https;',
            '        proxy_set_header Upgrade $http_upgrade;',
            '        proxy_set_header Connection $sokrat_pbx_connection;',
            '        proxy_redirect ~^http://127\\.0\\.0\\.1:\\d+/(.*)$ /$1;',
            '        proxy_read_timeout 3600s;',
            '        proxy_send_timeout 3600s;',
            '        proxy_buffering off;',
            '    }',
            '',
            '    location @sokrat_login {',
            f'        return 302 http://$host:{CONTROL_PORT}/control/;',
            '    }',
            '}',
            '',
        ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temporary = OUTPUT.with_name(OUTPUT.name + '.tmp')
    temporary.write_text('\n'.join(lines))
    os.chmod(temporary, 0o644)
    os.replace(temporary, OUTPUT)
    print(f'[pbx-proxy] generated {len(entries)} PBX dashboard listener(s) at {OUTPUT}')


if __name__ == '__main__':
    main()
